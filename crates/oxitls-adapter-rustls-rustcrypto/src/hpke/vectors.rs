//! Suites covered (all base mode, mode=0):
//!   A.1 — DHKEM(X25519,HKDF-SHA256) / HKDF-SHA256 / AES-128-GCM  (kem=0x20, kdf=0x01, aead=0x01)
//!   A.2 — DHKEM(X25519,HKDF-SHA256) / HKDF-SHA256 / ChaCha20Poly1305 (kem=0x20, kdf=0x01, aead=0x03)
//!   A.3 — DHKEM(P-256,HKDF-SHA256)  / HKDF-SHA256 / AES-128-GCM   (kem=0x10, kdf=0x01, aead=0x01)
